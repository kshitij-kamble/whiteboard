#!/usr/bin/env node
// Regenerates docs/STATE.md from backlog + phase notes + ADRs + activity.
//
//   node .claude/scripts/refresh-state.mjs            regenerate (prints a one-line summary)
//   node .claude/scripts/refresh-state.mjs --quiet    regenerate silently (Stop hook)
//   node .claude/scripts/refresh-state.mjs --check    exit 1 if STATE.md is stale, don't write
//   node .claude/scripts/refresh-state.mjs log <text> prepend a dated entry to activity.md, then regenerate
//
// Never throws on missing sources — an empty project just yields an empty snapshot.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOCS = path.join(ROOT, 'docs');
const P = {
  state: path.join(DOCS, 'STATE.md'),
  backlog: path.join(DOCS, 'backlog.md'),
  activity: path.join(DOCS, 'activity.md'),
  phases: path.join(DOCS, 'phases'),
  adr: path.join(DOCS, 'adr'),
};
const ACTIVITY_HEADER = '# Activity\n\nNewest first. One line per event. Not for commits — see `git log`.\n\n';

const read = (f) => { try { return fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n'); } catch { return ''; } };
const listDir = (d) => { try { return fs.readdirSync(d, { withFileTypes: true }); } catch { return []; } };
const today = () => new Date().toLocaleDateString('en-CA'); // YYYY-MM-DD, local time

function parseBacklog() {
  const items = [];
  const re = /^## (\S+)\s+<!-- id: (b-\d{8}-\d{3}) -->\s*$/gm;
  const text = read(P.backlog);
  const heads = [...text.matchAll(re)];
  heads.forEach((m, i) => {
    const body = text.slice(m.index + m[0].length, heads[i + 1]?.index ?? text.length);
    const field = (k) => body.match(new RegExp(`^- \\*\\*${k}:\\*\\*[ \\t]*(.*)$`, 'm'))?.[1].trim() ?? '';
    const statusLine = field('status');
    items.push({
      slug: m[1], id: m[2], tag: field('tag'), title: field('title') || m[1],
      status: statusLine.split(/\s/)[0] || 'open', statusNote: statusLine.split(' — ').slice(1).join(' — '),
      linked: field('linked-phase'),
    });
  });
  return items;
}

function parseFrontmatter(text) {
  const fm = text.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '';
  return Object.fromEntries(fm.split('\n').map((l) => l.match(/^(\w[\w-]*):\s*(.*?)\s*(#.*)?$/)).filter(Boolean).map((m) => [m[1], m[2]]));
}

function parsePhases() {
  return listDir(P.phases).filter((d) => d.isDirectory()).map((d) => {
    const meta = parseFrontmatter(read(path.join(P.phases, d.name, 'index.md')));
    return { folder: d.name, topic: meta.topic || d.name, status: meta.status || '?', updated: meta.updated || '', backlog: meta.backlog || '' };
  }).sort((a, b) => b.updated.localeCompare(a.updated));
}

function parseAdrs() {
  return listDir(P.adr).filter((d) => d.isFile() && /^\d{4}-.*\.md$/.test(d.name) && !d.name.startsWith('0000-')).map((d) => {
    const text = read(path.join(P.adr, d.name));
    return {
      file: d.name,
      title: text.match(/^# (.+)$/m)?.[1].trim() ?? d.name,
      status: text.match(/^(?:- )?\**status:?\**:?\s*(\w+)/im)?.[1].toLowerCase() ?? '?',
    };
  }).sort((a, b) => b.file.localeCompare(a.file));
}

function activityEntries() {
  return read(P.activity).split('\n').filter((l) => /^- \d{4}-\d{2}-\d{2}/.test(l));
}

function render() {
  const backlog = parseBacklog();
  const phases = parsePhases();
  const adrs = parseAdrs();
  const activity = activityEntries();
  const by = (s) => backlog.filter((b) => b.status === s);
  const out = [];

  out.push('# State', '', '<!-- Generated by .claude/scripts/refresh-state.mjs — do not hand-edit. Fix the sources, then /state refresh. -->', '');

  const active = phases.filter((p) => p.status !== 'done');
  out.push('## Active arcs', '');
  if (active.length) {
    out.push('| Topic | Phase | Updated | Backlog |', '|---|---|---|---|');
    for (const p of active) out.push(`| [${p.topic}](phases/${p.folder}/index.md) | ${p.status} | ${p.updated} | ${p.backlog} |`);
  } else out.push('_None._');
  out.push('');

  const counts = ['open', 'in-progress', 'done', 'dropped'].map((s) => `${s}: ${by(s).length}`).join(' · ');
  out.push('## Backlog', '', backlog.length ? counts : '_Empty._', '');
  const line = (b) => `- \`${b.id}\` **${b.title}** (${b.tag})${b.linked ? ` → ${b.linked}` : ''}`;
  if (by('in-progress').length) out.push('**In progress**', '', ...by('in-progress').map(line), '');
  if (by('open').length) out.push('**Open**', '', ...by('open').map(line), '');

  out.push('## Recent decisions', '');
  out.push(...(adrs.length ? adrs.slice(0, 5).map((a) => `- [${a.title}](adr/${a.file}) — ${a.status}`) : ['_None._']), '');

  out.push('## Recent activity', '');
  out.push(...(activity.length ? activity.slice(0, 10) : ['_None._']), '');

  return out.join('\n');
}

function refresh({ quiet }) {
  const next = render();
  if (read(P.state) !== next) {
    fs.mkdirSync(DOCS, { recursive: true });
    fs.writeFileSync(P.state, next);
    if (!quiet) console.log('STATE.md regenerated.');
  } else if (!quiet) console.log('STATE.md already up to date.');
}

const [cmd, ...rest] = process.argv.slice(2);
try {
  if (cmd === '--check') {
    if (read(P.state) === render()) { console.log('STATE.md is fresh.'); }
    else { console.log('STATE.md is stale — run /state refresh.'); process.exit(1); }
  } else if (cmd === 'log') {
    const text = rest.join(' ').trim();
    if (!text) { console.error('Usage: refresh-state.mjs log <text>'); process.exit(2); }
    const cur = read(P.activity) || ACTIVITY_HEADER;
    const idx = cur.search(/^- \d{4}-\d{2}-\d{2}/m);
    const entry = `- ${today()} — ${text.replace(/\s*\n\s*/g, ' ')}\n`;
    fs.mkdirSync(DOCS, { recursive: true });
    fs.writeFileSync(P.activity, idx === -1 ? cur.replace(/\n*$/, '\n\n') + entry : cur.slice(0, idx) + entry + cur.slice(idx));
    console.log(`Logged: ${entry.trim()}`);
    refresh({ quiet: false });
  } else {
    refresh({ quiet: cmd === '--quiet' });
  }
} catch (err) {
  // The Stop hook must never break a turn; report and exit cleanly.
  console.error(`refresh-state: ${err.message}`);
  process.exit(cmd === '--quiet' ? 0 : 2);
}
